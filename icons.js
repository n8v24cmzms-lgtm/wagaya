export function iconKeyFor(name, category) {
  const n = String(name || "");
  for (const [words, key] of FOOD_KEYWORDS) {
    if (words.some((w) => n.includes(w))) return key;
  }
  if (category && CATEGORY_ICONS[category]) return CATEGORY_ICONS[category];
  for (const [words, key] of NAME_GROUPS) {
    if (words.some((w) => n.includes(w))) return key;
  }
  return "cat_generic";
}

